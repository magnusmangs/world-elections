// Spjall: spurningar um landið eða fyrirtækið sem er opið. Svör koma eingöngu úr gögnum síðunnar (api/ask).
(function () {
  const L = (is, en) => (window.LANG === "en" ? en : is);
  const GENERAL = L("Fréttir og kosningar", "News and elections");
  const ctx = { kind: "general", id: "", label: GENERAL };
  let history = [];
  const el = (tag, cls, txt) => { const e = document.createElement(tag); if (cls) e.className = cls; if (txt != null) e.textContent = txt; return e; };

  const ASK = L("Spyrja", "Ask");
  const fab = el("button", "chat-fab", ASK);
  fab.type = "button"; fab.setAttribute("aria-haspopup", "dialog");
  const box = el("section", "chat-box"); box.hidden = true;
  box.setAttribute("role", "dialog"); box.setAttribute("aria-label", L("Spyrja um gögnin", "Ask about the data"));
  box.innerHTML = `<div class="chat-head"><div><strong>${ASK}</strong><span class="chat-about"></span></div>
    <button type="button" class="chat-close">${L("Loka", "Close")}</button></div>
    <div class="chat-log" aria-live="polite"></div>
    <form class="chat-form"><label class="visually-hidden" for="chat-q">${L("Spurning", "Question")}</label>
    <textarea id="chat-q" maxlength="500" placeholder="${L("Skrifaðu spurningu…", "Type a question…")}"></textarea><button type="submit">${L("Senda", "Send")}</button></form>
    <p class="chat-note">${L("Svör eru búin til af gervigreind eingöngu úr gögnum síðunnar og geta verið röng. Athugaðu heimildirnar. Ekki fjárfestingarráðgjöf. Spurningar eru ekki vistaðar.", "Answers are generated by AI from the site's own data only and may be wrong. Check the sources. Not investment advice. Questions are not stored.")}</p>`;
  document.body.append(fab, box);
  const log = box.querySelector(".chat-log"), about = box.querySelector(".chat-about");
  const form = box.querySelector("form"), q = box.querySelector("textarea"), send = form.querySelector("button");

  const SUGG = {
    country: () => L(["Hvenær eru næstu kosningar?", "Hverjir eru helstu flokkarnir og hvar standa þeir?", "Hvað segja nýjustu fréttir?"],
      ["When is the next election?", "Who are the main parties and where do they stand?", "What does the latest news say?"]),
    company: () => L(["Hvernig var síðasti ársfjórðungur?", "Hvernig hafa tekjur þróast síðasta árið?", "Hvað kom fram í nýjustu afkomutilkynningu?"],
      ["How was the last quarter?", "How has revenue developed over the past year?", "What did the latest earnings release say?"]),
    general: () => L(["Hvaða kosningar eru næstar?", "Hvað er helst í fréttum?"], ["Which elections are next?", "What are the top stories?"]),
  };

  // Turn plain URLs in the answer into links, safely.
  function render(text, node) {
    const parts = String(text).split(/(https?:\/\/[^\s)<>\]]+)/g);
    parts.forEach((p, i) => {
      if (i % 2) { const a = el("a", null, p.replace(/^https?:\/\/(www\.)?/, "").slice(0, 60)); a.href = p; a.target = "_blank"; a.rel = "noopener"; node.append(a); }
      else node.append(document.createTextNode(p));
    });
  }
  function add(role, text) { const m = el("div", `chat-msg ${role}`); render(text, m); log.append(m); log.scrollTop = log.scrollHeight; return m; }
  function reset() {
    history = []; log.textContent = "";
    about.textContent = `${L("Spurt um", "Asking about")}: ${ctx.label}`;
    add("bot", ctx.kind === "general" ? L("Spyrðu um kosningar eða fréttir. Opnaðu land eða fyrirtæki til að spyrja nánar um það.", "Ask about elections or the news. Open a country or company to ask about it in detail.")
      : L(`Spyrðu um ${ctx.label}. Ég svara aðeins út frá gögnunum hér á síðunni og vísa í heimildir.`, `Ask about ${ctx.label}. I answer only from the data on this site and cite the sources.`));
    const s = el("div", "chat-sugg");
    (SUGG[ctx.kind] || SUGG.general)(ctx.label).forEach((t) => { const b = el("button", null, t); b.type = "button"; b.onclick = () => ask(t); s.append(b); });
    log.append(s);
  }
  async function ask(text) {
    text = text.trim(); if (!text || send.disabled) return;
    log.querySelectorAll(".chat-sugg").forEach((n) => n.remove());
    add("me", text); q.value = ""; send.disabled = true;
    const wait = add("bot wait", L("Hugsa…", "Thinking…"));
    let answer;
    try {
      const r = await fetch("/api/ask", { method: "POST", headers: { "content-type": "application/json" },
        body: JSON.stringify({ question: text, lang: window.LANG || "is", context: { kind: ctx.kind, id: ctx.id }, history }) });
      const d = await r.json().catch(() => ({}));
      answer = d.answer || L("Ekki tókst að ná í svar.", "Could not get an answer.");
      if (r.ok) history.push({ role: "user", content: text }, { role: "assistant", content: answer });
    } catch (_) { answer = L("Engin tenging. Reyndu aftur.", "No connection. Try again."); }
    wait.remove(); add("bot", answer); send.disabled = false; q.focus();
  }

  function setContext(kind, id, label) {
    const changed = kind !== ctx.kind || id !== ctx.id;
    Object.assign(ctx, { kind: kind || "general", id: id || "", label: label || GENERAL });
    fab.textContent = ctx.kind === "general" ? ASK : `${L("Spyrja um", "Ask about")} ${ctx.label}`;
    if (changed) reset();
  }
  window.chatContext = setContext;

  fab.onclick = () => { box.hidden = false; fab.hidden = true; q.focus(); };
  box.querySelector(".chat-close").onclick = () => { box.hidden = true; fab.hidden = false; fab.focus(); };
  box.addEventListener("keydown", (e) => { if (e.key === "Escape") { e.stopPropagation(); box.querySelector(".chat-close").click(); } });
  form.onsubmit = (e) => { e.preventDefault(); ask(q.value); };
  q.addEventListener("keydown", (e) => { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); ask(q.value); } });
  reset();
})();
